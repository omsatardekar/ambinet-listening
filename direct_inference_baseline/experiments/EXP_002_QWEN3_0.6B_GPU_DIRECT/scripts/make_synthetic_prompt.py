"""Builds a deterministic SYNTHETIC, NON-CLINICAL long prompt (~4,000 tokens after the chat template) for the long-context speed test.
Content: a fake warehouse inventory list plus a retrieval question whose answer is known. No dataset, transcripts, labels or clinical text."""
import hashlib, json, random
from pathlib import Path
from transformers import AutoTokenizer

E = Path(__file__).resolve().parents[1]
MODEL = E / "models" / "Qwen3-0.6B-ov-fp16"
TARGET, TOL = 4000, 60
ITEMS = ["copper kettle", "wooden ladder", "glass jar", "steel hammer", "wool blanket", "paper lantern", "brass key", "clay pot", "rope coil",
         "tin bucket", "oak barrel", "silk scarf", "iron anvil", "straw hat", "canvas tent", "bamboo basket", "leather belt", "stone mortar",
         "silver spoon", "cotton rug", "plastic funnel", "rubber boot", "ceramic tile", "linen sheet", "granite slab", "nylon cord", "pine plank"]
tok = AutoTokenizer.from_pretrained(str(MODEL))


def build(n):
    rnd = random.Random(20261112)
    recs = []
    for i in range(1, n + 1):
        recs.append({"n": i, "item": rnd.choice(ITEMS), "code": f"{rnd.choice('ABCDEFGHJKLMNPQRSTUVWXYZ')}{rnd.choice('ABCDEFGHJKLMNPQRSTUVWXYZ')}-{rnd.randint(1000, 9999)}",
                     "shelf": f"{rnd.choice('ABCDEFGH')}{rnd.randint(1, 20)}"})
    body = "\n".join(f"Record {r['n']:04d}: item={r['item']}, code={r['code']}, shelf={r['shelf']}." for r in recs)
    q = ("The text above is a warehouse inventory list. List the item name and code of Record 0001 through Record 0005, one per line "
         f"in the form 'Record 0001: item, code'. Then state the item name of Record {n:04d}.")
    user = "Inventory list:\n" + body + "\n\n" + q
    text = tok.apply_chat_template([{"role": "user", "content": user}], tokenize=False, add_generation_prompt=True, enable_thinking=False)
    return recs, user, text, len(tok(text, add_special_tokens=False)["input_ids"]), q


lo, hi = 50, 400
while lo < hi:                                   # smallest record count reaching the target
    mid = (lo + hi) // 2
    if build(mid)[3] >= TARGET:
        hi = mid
    else:
        lo = mid + 1
recs, user, text, ntok, q = build(lo)
assert abs(ntok - TARGET) <= TOL, ntok
expected = {"first5": [f"Record {r['n']:04d}: {r['item']}, {r['code']}" for r in recs[:5]], "last_record": recs[-1]["n"], "last_item": recs[-1]["item"]}
out = {"n_records": lo, "prompt_tokens_with_chat_template": ntok, "user_message_sha256": hashlib.sha256(user.encode()).hexdigest(), "user_message": user, "expected": expected,
       "note": "synthetic non-clinical; generated by scripts/make_synthetic_prompt.py with a fixed seed"}
R = E / "results"
R.mkdir(exist_ok=True)
(R / "longctx_prompt.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
print(json.dumps({k: v for k, v in out.items() if k != "user_message"}, indent=1))
