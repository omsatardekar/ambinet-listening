"""Builds the ONE file to upload as the scoring script in the Azure ML Studio deployment wizard (the wizard takes a single file, not a folder).

    python azure_ml_h1/build_single_file_score.py        (from the repository root; any Python 3.10+; standard library only)

1. assembles a bundle in azure_ml_h1/code_bundle/: score.py + the existing prompt builder, parser, schema validator, evidence resolver and schemas (copied, not edited)
   + the frozen H1 prompt (SHA-256 verified);
2. embeds the bundle as a base64 ZIP in azure_ml_h1/score_single_file.py. At start-up that file unpacks the bundle to a temp folder and hands init()/run() to the real score.py,
   which still checks the prompt hash and the model-weights hash.
"""
import base64
import hashlib
import io
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "code_bundle"
H1_PROMPT = ROOT / "direct_inference_baseline" / "experiments" / "EXP_008_QWEN3_0.6B_HYBRID_P02_S1" / "prompts" / "H1_hybrid_prompt.txt"
H1_SHA = "dc10ba065c9f1acaa237d106bd97b451ddfe1efcd94117b727d6585511f79cd8"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def ignore(_dir, names):
    return [n for n in names if n == "__pycache__" or n.endswith(".pyc")]


def main() -> int:
    if sha(H1_PROMPT) != H1_SHA:
        sys.exit(f"H1 prompt hash mismatch: {sha(H1_PROMPT)}")
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    shutil.copy(HERE / "score.py", OUT / "score.py")
    for rel in ("direct_inference_baseline/__init__.py", "direct_inference_baseline/config", "direct_inference_baseline/inference", "direct_inference_baseline/evaluation",
                "clinical_extraction_schema.json", "dataset_v2_batch_001_corrected/schema/final_label_schema.json"):
        src, dst = ROOT / rel, OUT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(src, dst, ignore=ignore) if src.is_dir() else shutil.copy(src, dst)
    (OUT / "clinical_extraction").mkdir()
    for f in ("__init__.py", "config.py", "compact.py", "evidence.py"):
        shutil.copy(ROOT / "clinical_extraction" / f, OUT / "clinical_extraction" / f)
    shutil.copy(H1_PROMPT, OUT / "H1_hybrid_prompt.txt")
    if sha(OUT / "H1_hybrid_prompt.txt") != H1_SHA:
        sys.exit("bundle prompt hash mismatch")

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(OUT.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(OUT).as_posix())
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    tag = hashlib.sha256(buf.getvalue()).hexdigest()[:12]
    template = '''"""Self-contained Azure ML scoring script for Qwen3-0.6B + frozen H1 prompt (generated by build_single_file_score.py). Embeds the code bundle; delegates to the real score.py. Do not edit."""
import base64, importlib.util, io, os, sys, tempfile, zipfile

_B64 = "%(b64)s"
_DIR = os.path.join(tempfile.gettempdir(), "h1_bundle_%(tag)s")
if not os.path.exists(os.path.join(_DIR, "score.py")):
    zipfile.ZipFile(io.BytesIO(base64.b64decode(_B64))).extractall(_DIR)
sys.path.insert(0, _DIR)
_spec = importlib.util.spec_from_file_location("h1_score", os.path.join(_DIR, "score.py"))
_mod = importlib.util.module_from_spec(_spec)
sys.modules["h1_score"] = _mod
_spec.loader.exec_module(_mod)
init = _mod.init
run = _mod.run
'''
    target = HERE / "score_single_file.py"
    target.write_text(template % {"b64": b64, "tag": tag}, encoding="utf-8")
    print(f"written {target}  ({target.stat().st_size / 1024:.0f} KB, bundle id {tag}; H1 prompt hash verified)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
